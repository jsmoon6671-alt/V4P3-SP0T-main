"""Generate small route-specific HTML documents from the shared page template."""

from pathlib import Path

from bs4 import BeautifulSoup, Comment


ROOT = Path(__file__).resolve().parent
STATIC = ROOT / "static"
TEMPLATE = ROOT / "page-template.html"

PAGES = {
    "index.html": ("home", {"home"}),
    "store.html": ("store", {"store"}),
    "events.html": ("events", {"events"}),
    "notices.html": ("notices", {"notices"}),
    "support.html": ("support", {"support"}),
    "account.html": ("account", {"account"}),
    "review-write.html": ("review-write", {"review-write"}),
    "ranking.html": ("ranking", {"ranking"}),
    "tiers.html": ("tiers", {"tiers"}),
    "terms.html": ("terms", {"terms"}),
    "tracking.html": ("tracking", {"tracking"}),
    "cart.html": ("cart", {"cart", "complete"}),
    "admin.html": ("admin", {"admin"}),
    "admin-test.html": ("admin-test", {"admin-test"}),
    "subadmin-panel.html": ("subadmin-panel", {"subadmin-panel"}),
}

PATHS = {
    "home": "/",
    "store": "/store",
    "events": "/events",
    "notices": "/notices",
    "support": "/support",
    "account": "/account",
    "review-write": "/review-write",
    "ranking": "/ranking",
    "tiers": "/tiers",
    "terms": "/terms",
    "tracking": "/tracking",
    "cart": "/cart",
    "complete": "/cart#complete",
    "admin": "/admin",
    "admin-test": "/admin-test",
    "subadmin-panel": "/subadmin-panel",
}


def build() -> None:
    source = TEMPLATE.read_text(encoding="utf-8")
    for filename, (active_page, included_pages) in PAGES.items():
        soup = BeautifulSoup(source, "html.parser")
        soup.body["data-page"] = active_page
        for section in soup.select("section.page"):
            page_id = section.get("id", "")
            if page_id not in included_pages:
                section.decompose()
                continue
            classes = [name for name in section.get("class", []) if name != "active"]
            if page_id == active_page:
                classes.append("active")
            section["class"] = classes
        for link in soup.select('a[href^="#"]'):
            page_id = link.get("href", "")[1:]
            if page_id in PATHS:
                link["href"] = PATHS[page_id]
        soup.html.insert(0, Comment(" Generated by web/build_pages.py; edit web/page-template.html "))
        (STATIC / filename).write_text(str(soup), encoding="utf-8")


if __name__ == "__main__":
    build()
